"""Regenerate js/seed-syllabus.js from syllabus-2026-27.yaml.
Usage: python tools/gen_seed.py   (needs PyYAML: pip install pyyaml)"""
import json, re, sys, os
sys.path[:0] = [p for p in sys.argv[1:]]          # optional extra lib path
import yaml
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = yaml.safe_load(open(os.path.join(root, "syllabus-2026-27.yaml"), encoding="utf-8"))
COLOURS = {"maths": "#E8002D", "science": "#C98500", "english": "#3671C6", "malayalam": "#1AA88C", "sst": "#B05FD6"}  # validated: dataviz validate_palette.js, dark, surface #1F1F2B
def slug(s): return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40]
subjects = []
for s in src["subjects"]:
    units = []
    for u in s.get("units", []):
        m = u["marks"]
        if isinstance(m, str):  # "18 + 2 map"
            m = sum(int(x) for x in re.findall(r"\d+", m))
        units.append({"name": u["unit"], "marks": m})
    chapters = []
    for i, c in enumerate(s.get("chapters", [])):
        b = c.get("board", True)
        chapters.append({
            "id": s["id"] + "-" + slug(c["name"]),
            "name": c["name"], "unit": c.get("unit", ""),
            "compound": c.get("compound", "medium"),
            "board": "partial" if b == "partial" else ("internal" if b == "internal" else bool(b)),
            "kind": c.get("kind", "chapter"),
            "note": c.get("note", ""),
        })
    subjects.append({"id": s["id"], "name": s["name"], "code": str(s.get("code", "")),
                     "exam": str(s["exam"]), "colour": COLOURS.get(s["id"], "#888"),
                     "units": units, "chapters": chapters})
out = {"session": src["meta"]["session"], "source": "CBSE curriculum 2026-27 + date sheet 06.11.2026", "subjects": subjects}
js = "// GENERATED by tools/gen_seed.py from syllabus-2026-27.yaml: do not edit by hand.\n" \
     "// Public syllabus data only. No personal data lives here.\n" \
     "export const SEED = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
open(os.path.join(root, "js", "seed-syllabus.js"), "w", encoding="utf-8", newline="\n").write(js)
print("wrote js/seed-syllabus.js:", {s["id"]: len(s["chapters"]) for s in subjects})
